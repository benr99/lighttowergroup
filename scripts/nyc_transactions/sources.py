def classify_mortgage_doc_type(doc_type: str, raw_notes: str = "") -> tuple[bool, bool]:
    """Return (is_cema, is_modification_only) for an ACRIS mortgage document type."""
    code = (doc_type or "").strip().upper()
    notes_upper = (raw_notes or "").upper()
    if code in {"AGMT", "M&CON", "CEMA"} or "CEMA" in notes_upper or "CONSOLIDATION" in notes_upper:
        if "NO NEW MONEY" in notes_upper or "MODIFICATION ONLY" in notes_upper:
            return False, True
        return True, False
    if code in {"AL&R", "ASST", "MOD"}:
        return False, True
    return False, False


def _make_deal(
    tx_id: str,
    address: str,
    borough: str,
    neighborhood: str,
    bbl: str,
    bldg_class: str,
    asset_type: str,
    gsf: int,
    lot_sqft: int,
    units: int,
    res_units: int,
    stories: int,
    year_built: int,
    zoning: str,
    price: float,
    closing_date: str,
    recorded_date: str,
    buyer: str,
    seller: str,
    broker: str,
    doc_id: str,
    mtg_doc_id: str,
    mtg_type: str,
    mtg_amount: float,
    lender: str,
    prior_date: str,
    prior_price: float,
    noi: float | None,
    scene_hook: str,
    street_context: str,
    subhead_1: str,
    desk_kicker: str,
) -> NycTransactionDossier:
    mortgages = []
    if mtg_amount > 0:
        mortgages.append(
            MortgageRecord(
                document_id=mtg_doc_id,
                instrument_type=mtg_type,
                amount_usd=mtg_amount,
                lender=lender,
                recorded_date=recorded_date,
                is_modification_or_assignment_only=False,
            )
        )
    priors = []
    if prior_price > 0 and prior_date:
        priors.append(
            PriorSaleRecord(
                closing_date=prior_date,
                price_usd=prior_price,
                document_id=f"{prior_date.replace('-', '')}00192001",
                same_scope=True,
            )
        )
    b_parts = bbl.split("-")
    zola_url = (
        f"https://zola.planning.nyc.gov/l/lot/{b_parts[0]}/{int(b_parts[1])}/{int(b_parts[2])}"
        if len(b_parts) == 3 and b_parts[1].isdigit() and b_parts[2].isdigit()
        else "https://zola.planning.nyc.gov/"
    )
    return NycTransactionDossier(
        transaction_id=tx_id,
        property_info=PropertyIdentity(
            address=address,
            borough=borough,
            neighborhood=neighborhood,
            bbl=bbl,
            building_class=bldg_class,
            asset_type=asset_type,
            gross_sqft=gsf,
            lot_sqft=lot_sqft,
            buildable_sqft=gsf,
            total_units=units,
            residential_units=res_units,
            stories=stories,
            year_built=year_built,
            zoning=zoning,
            is_single_condo_or_coop_unit=False,
        ),
        sale_price_usd=price,
        closing_date=closing_date,
        recorded_date=recorded_date,
        buyer=buyer,
        seller=seller,
        broker=broker,
        noi_usd=noi,
        mortgages=mortgages,
        prior_sales=priors,
        sources=[
            {
                "name": f"NYC ACRIS Real Property Registry — Deed #{doc_id} ({address}, BBL {bbl})",
                "url": "https://a836-acris.nyc.gov/DS/DocumentSearch/BBL",
            },
            {
                "name": f"NYC Department of City Planning PLUTO — {address} (BBL {bbl})",
                "url": zola_url,
            },
        ],
        notes=[scene_hook, street_context, f"SUBHEAD::{subhead_1}", f"KICKER::{desk_kicker}"],
    )


